const express = require("express");
const { uploadImage } = require("../controllers/uploadController");
const announcements = require("../controllers/announcementController");
const { receiveImage } = require("../middleware/upload");
const admin = require("../controllers/adminController");
const { requireAdmin } = require("../middleware/auth");
const { auditAdminMutation } = require("../middleware/adminAudit");
const { getContent, updateContent } = require("../controllers/siteContentController");

const router = express.Router();
router.use(requireAdmin);
router.use(auditAdminMutation);
router.get("/site-content", getContent);
router.patch("/site-content", updateContent);
router.get("/stats", admin.getStats);
router.get("/orders", admin.listAllOrders);
router.patch("/orders/:id/status", admin.updateOrderStatus);
router.patch("/orders/:id/payment-status", admin.updatePaymentStatus);
router.patch("/orders/:id/appointment-status", admin.updateAppointmentStatus);
router.delete("/orders/:id", admin.cancelOrder);
router.get("/order-change-requests", admin.listOrderChangeRequests);
router.patch("/order-change-requests/:id", admin.reviewOrderChangeRequest);
router.post("/uploads/images", receiveImage, uploadImage);
router.get("/announcements", announcements.listAll);
router.post("/announcements", announcements.create);
router.patch("/announcements/:id", announcements.update);
router.delete("/announcements/:id", announcements.remove);
router.get("/products", admin.listAllProducts);
router.post("/products", admin.createProduct);
router.patch("/products/:id", admin.updateProduct);
router.delete("/products/:id", admin.deleteProduct);
router.get("/categories", admin.listCategoriesAdmin);
router.post("/categories", admin.createCategory);
router.patch("/categories/:id", admin.updateCategory);
router.delete("/categories/:id", admin.deleteCategory);
router.get("/users", admin.listUsers);
router.post("/users", admin.createUser);
router.patch("/users/:id", admin.updateUser);
router.patch("/users/:id/role", admin.updateUserRole);
router.patch("/users/:id/password", admin.updateUserPassword);
// Alias POST dipakai UI agar aksi tetap diteruskan oleh reverse proxy/hosting
// yang tidak mengizinkan method DELETE. Route DELETE dipertahankan untuk REST API.
router.post("/users/:id/delete", admin.deleteUser);
router.delete("/users/:id", admin.deleteUser);
router.get("/reviews", admin.listReviews);
router.patch("/reviews/:id", admin.moderateReview);
router.get("/coupons", admin.listCoupons);
router.post("/coupons", admin.createCoupon);
router.patch("/coupons/:id", admin.updateCoupon);
router.delete("/coupons/:id", admin.deleteCoupon);
router.get("/schedule-settings", admin.getScheduleSettings);
router.patch("/schedule-settings", admin.updateScheduleSettings);
router.get("/therapists", admin.listTherapists);
router.post("/therapists", admin.createTherapist);
router.patch("/therapists/:id", admin.updateTherapist);
router.delete("/therapists/:id", admin.deleteTherapist);
router.get("/newsletter-subscribers", admin.listNewsletterSubscribers);
router.delete("/newsletter-subscribers/:id", admin.removeNewsletterSubscriber);
router.get("/reports/sales", admin.salesReport);
router.get("/audit-logs", admin.listAuditLogs);

module.exports = router;
